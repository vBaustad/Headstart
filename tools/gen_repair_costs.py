"""Generate Data/RepairCosts.lua (for Trainer.lua): what a point of durability costs to repair.

    python tools/gen_repair_costs.py [schema]      (default: the newest wow_classic_beta build)

From the game's tables: durabilitycosts (copper per point, by item level, one column per weapon
subclass and per armour subclass) and durabilityquality (a factor, by (item quality + 1) * 2). The
columns that are the same at every item level are written once, and each subclass points at its
list:
    YR.RepairCosts = { quality = { [quality] = factor }, weapon = { [subclass] = list },
                       armor = { [subclass] = list }, [list] = { copper by item level } }
A subclass that costs nothing to repair (a ring's, a relic's) has no entry.
"""
import os
import sys

import duckdb

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB = r"S:\forever-data\db\forever.duckdb"
OUT = os.path.join(ROOT, "Data", "RepairCosts.lua")
WEAPONS, ARMOUR = 21, 8


def main():
    c = duckdb.connect(DB, read_only=True)
    s = sys.argv[1] if len(sys.argv) > 1 else c.sql(
        "select schema_name from main.builds where schema_name like 'wow_classic_beta_%' order by schema_name desc limit 1").fetchone()[0]
    rows = {int(r[0]): [int(x) for x in r[1:]] for r in c.sql(f"select * from {s}.durabilitycosts").fetchall()}
    top = max(rows)
    assert sorted(rows) == list(range(1, top + 1)), "item levels missing from durabilitycosts"
    assert len(rows[1]) == WEAPONS + ARMOUR, "durabilitycosts has other columns than 21 weapon and 8 armour costs"
    factor = {int(i): float(v) for i, v in c.sql(f"select ID, Data from {s}.durabilityquality").fetchall()}
    quality = {q: factor[(q + 1) * 2] for q in range(0, 8) if factor.get((q + 1) * 2)}

    lists, weapon, armor = [], {}, {}
    for k in range(WEAPONS + ARMOUR):
        col = [rows[i][k] for i in range(1, top + 1)]
        if not any(col):
            continue
        if col not in lists:
            lists.append(col)
        n = lists.index(col) + 1
        if k < WEAPONS:
            weapon[k] = n
        else:
            armor[k - WEAPONS] = n

    def num(v):
        return ("%g" % v)

    def keyed(d):
        return "{ " + ", ".join(f"[{k}] = {v}" for k, v in sorted(d.items())) + " }"

    lines = [f"-- GENERATED by tools/gen_repair_costs.py from {s}. Do not edit; regenerate.",
             "-- What one point of durability costs to repair, in copper, by item level (durabilitycosts), one list",
             "-- for each kind of item; which list a weapon or armour subclass uses; and the factor for the item's",
             "-- quality (durabilityquality). An item's repair: points lost * its list at its item level * factor.",
             "local _, YR = ...",
             "YR.RepairCosts = {",
             "    quality = " + keyed({q: num(v) for q, v in quality.items()}) + ",",
             "    weapon = " + keyed(weapon) + ",",
             "    armor = " + keyed(armor) + ","]
    for col in lists:
        lines.append("    { " + ", ".join(str(v) for v in col) + " },")
    lines += ["}", ""]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print(f"{len(lists)} cost lists, item levels 1-{top}, from {s}")


if __name__ == "__main__":
    main()
